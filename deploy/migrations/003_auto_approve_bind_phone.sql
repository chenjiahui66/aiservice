-- =====================================================================
-- 003_auto_approve_bind_phone —— 注册即通过 + 主页电话绑定账号手机号
--
-- 背景（两件事一起做，因为都落在同一批存量数据上）：
--
--   1) 以前服务者注册后要人工审核才能对外接单。现在改成「注册即通过」，
--      出问题的服务者由平台在后台「停用」处理（enabled=DISABLED 会同时
--      禁掉登录账号、让推广码立即失效）。
--      存量库里还卡在 PENDING 的服务者在这里直接放行 ——
--      不放行的话，他们永远扫不了自己的码，等于被永久卡在门外。
--
--   2) 对外联系电话以前要服务者自己在「编辑主页」里手填，
--      实际上没人填 → 客户在主页上看不到电话，打不了电话。
--      现在注册 / 登录时由后端把账号手机号作为默认值写进去，存量数据在这里补齐。
--      （只是「默认值」：服务者之后想换成别的号码，在「编辑主页」里改即可。）
--
-- 为什么不写进 sql/schema.sql：
--   schema.sql 只在数据卷首次初始化时执行一次，存量环境补不上，
--   必须走迁移目录（见 001_user_consents.sql 开头的原因说明）。
--
-- 本脚本可重复执行：两条都是「只补缺口」的语义，跑第二遍不会改坏数据。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 存量「待审核」服务者直接放行
--    audit_status: 0=待审核 1=已通过 2=已驳回 3=已暂停
-- ---------------------------------------------------------------------
UPDATE `providers`
SET `audit_status` = 1,
    `audited_at`  = NOW()
WHERE `audit_status` = 0
  AND `deleted` = 0;

-- ---------------------------------------------------------------------
-- 2. 存量服务主页绑定账号手机号
--    只补空号，不覆盖服务者自己填过的号码。
-- ---------------------------------------------------------------------
UPDATE `service_pages` sp
JOIN `providers` p ON p.id = sp.provider_id
JOIN `users` u ON u.id = p.user_id
SET sp.`contact_phone` = u.phone
WHERE (sp.`contact_phone` IS NULL OR sp.`contact_phone` = '')
  AND u.phone IS NOT NULL
  AND u.phone <> ''
  AND sp.deleted = 0;
