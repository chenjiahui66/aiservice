-- =====================================================================
-- 002_promo_video —— 推广指导视频地址（改为后台可配置）
--
-- 背景：原先视频地址硬编码在 miniapp/src/constants/promo-video.ts，
--        每次换地址都要改代码 + 重新发小程序版，太重。
--        改为存在 system_settings 里，管理员在「系统基础设置」页直接改，
--        小程序每次进「我的推广」页从后端取，改完刷新即生效。
--
-- 为什么不写进 sql/schema.sql：
--   schema.sql 只在数据卷首次初始化时执行一次，存量环境补不上，
--   必须走迁移目录（见 001_user_consents.sql 开头的原因说明）。
--
-- 本脚本必须可重复执行：用 INSERT IGNORE，靠 uk_settings_key 去重。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 设置项：推广指导视频的 https 直链
--
--    默认留空 = 小程序不显示「视频推广指导」入口。
--    这样在管理员配置之前，小程序里不会出现一个点开就是黑屏的假入口。
-- ---------------------------------------------------------------------
INSERT IGNORE INTO `system_settings`
  (`setting_key`, `setting_value`, `description`, `created_at`, `updated_at`, `deleted`)
VALUES
  ('promo.video.url', '',
   '推广指导视频的 https 直链（留空则小程序不显示该入口）',
   NOW(), NOW(), 0);
